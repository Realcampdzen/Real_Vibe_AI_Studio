/**
 * Получить данные услуги по ID
 * @param {number} id - ID услуги (0-7)
 * @returns {Object|null} Данные услуги или null если не найдена
 */
function getServiceById(id) {
  const serviceId = parseInt(id);
  if (isNaN(serviceId) || serviceId < 0 || serviceId >= SERVICES_DATA.length) {
    return null;
  }
  return SERVICES_DATA[serviceId];
}

