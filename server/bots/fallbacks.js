/**
 * Получить fallback-ответ для бота.
 * @param {string} botId - ID бота
 * @param {string} message - Сообщение пользователя
 * @returns {string} Fallback-ответ
 */
function getFallbackResponse(botId, message) {
  const responses = FALLBACKS[botId];
  if (!responses) return 'Извините, временные неполадки. Обращайтесь к @Stivanovv!';

  const lowerMessage = (message || '').toLowerCase();

  for (const [key, response] of Object.entries(responses)) {
    if (key !== 'default' && lowerMessage.includes(key)) {
      return response;
    }
  }

  return responses.default || 'Извините, временные неполадки. Обращайтесь к @Stivanovv!';
}

