import { listCatalogServices, searchCatalogServices } from '../services/catalog.js';

const CATALOG_INTENT_RE = /(услуг|товар|продукт|прайс|цен|стоим|сколько|бюджет|заказать|сайт|бот|агент|вайбкод|ролик|видео|smm|смм|контент|музык|озвуч|анимац|фото|mvp|saas|прилож|лендинг)/i;

function buildCatalogFallback(botId, message) {
  const text = String(message || '').trim();
  if (!CATALOG_INTENT_RE.test(text)) return null;

  const matches = searchCatalogServices(text, { limit: 3 });
  const services = matches.length > 0 ? matches : listCatalogServices();
  const limitedServices = matches.length > 0 ? services : services.slice(0, 12);
  const introByBot = {
    'bro-cat': 'Мяу, держу актуальный прайс по витрине Real Vibe:',
    valyusha: 'Смотри, вот актуальные направления и цены Real Vibe:',
    'health-assistant': 'По продуктам студии ориентирую так:',
  };
  const intro = introByBot[botId] || 'Актуальные услуги и цены Real Vibe:';
  const serviceLines = limitedServices.map((service) => (
    `${service.title} — ${service.priceLabel}. ${service.url}`
  ));

  return `${intro}\n${serviceLines.join('\n')}\nФинальная смета зависит от задачи, объёма, материалов, интеграций и сроков. Для точной оценки напишите @Stivanovv.`;
}

