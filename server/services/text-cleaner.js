/**
 * Утилиты очистки текста от markdown-разметки.
 * Раньше дублировался 4 раза в server.js.
 */

/**
 * Убирает markdown форматирование из текста ответа бота.
 * @param {string} text - Текст для очистки
 * @returns {string} Очищенный текст
 */
export function stripMarkdown(text) {
  if (!text) return '';
  return text
    .replace(/\*\*(.*?)\*\*/g, '$1')  // **жирный** → жирный
    .replace(/__(.*?)__/g, '$1')       // __подчёркивание__ → подчёркивание
    .replace(/\*(.*?)\*/g, '$1')       // *курсив* → курсив
    .replace(/~~(.*?)~~/g, '$1');      // ~~зачёркивание~~ → зачёркивание
}
